<?php

declare(strict_types=1);

namespace RSSBridge\Middlewares;

use RSSBridge\Caches\CacheInterface;
use RSSBridge\Http\FeedDeadline;
use RSSBridge\Http\Request;
use RSSBridge\Http\Response;

final class CacheMiddleware implements Middleware
{
    public const CACHE_TTL_HEADER = 'x-rssbridge-cache-ttl';
    private const REGENERATION_LOCK_TTL = 120;
    private const DEFAULT_MAX_AGE = 3600;
    private const COLD_WAIT_MS = 2000;
    private const COLD_POLL_MS = 100;
    private const BACKOFF_KEY_SUFFIX = '|backoff';
    private const STALE_MIN_MAX_AGE = 60;

    private CacheInterface $cache;

    public function __construct(CacheInterface $cache)
    {
        $this->cache = $cache;
    }

    /**
     * HTTP caching layer for display requests: conditional 304, fresh/stale
     * serving, single-flight regeneration, and a server-side backoff marker
     * that shields upstream during transient failures. Per-feed errors are
     * never normalised to 429/503 (FreshRSS would cooldown the whole domain).
     */
    public function __invoke(Request $request, callable $next): Response
    {
        $action = $request->get('action', 'frontpage');
        if ($action !== 'display') {
            $response = $next($request);
            if ($response->getCode() === 200) {
                $maxAge = in_array($action, ['health', 'connectivity'], true) === true ? 0 : self::DEFAULT_MAX_AGE;
                $response = $this->attachCacheHeaders($response, $maxAge);
            }
            return $response;
        }

        $feedTimeoutRaw = getenv('FEED_TIMEOUT');
        $feedTimeout = ($feedTimeoutRaw !== false && $feedTimeoutRaw !== '' && (int) $feedTimeoutRaw > 0) ? (int) $feedTimeoutRaw : 18;
        FeedDeadline::begin($feedTimeout);

        $cacheKey = $request->getCacheKey();
        $customTimeoutEnabled = filter_var(getenv('CACHE_CUSTOM_TIMEOUT'), FILTER_VALIDATE_BOOLEAN);
        $bypassCache = $customTimeoutEnabled === true && self::toInt($request->get('_cache_timeout', -1), -1) === 0;

        $lockAcquired = false;
        $staleResponse = null;

        if ($bypassCache === false) {
            $entry = $this->cache->getWithStale($cacheKey);
            $freshResponse = $entry['fresh'] ?? null;

            if ($freshResponse instanceof Response) {
                if ($freshResponse->getCode() === 200) {
                    $notModified = $this->createNotModifiedResponse($request, $freshResponse);
                    if ($notModified !== null) {
                        return $notModified;
                    }
                }
                return $this->attachCacheHeaders($freshResponse, $this->resolveMaxAge($request, $freshResponse), $freshResponse->getHeader('etag'));
            }

            $staleCandidate = $entry['stale'] ?? null;
            $staleResponse = $staleCandidate instanceof Response ? $staleCandidate : null;

            $backoff = $this->readBackoff($cacheKey);
            if ($backoff !== null) {
                return $this->serveBackoff($backoff, $staleResponse);
            }

            if ($staleResponse !== null && $staleResponse->getCode() === 200) {
                if ($this->cache->acquireLock($cacheKey, self::REGENERATION_LOCK_TTL) === false) {
                    return $this->attachStaleHeaders($staleResponse, self::STALE_MIN_MAX_AGE);
                }
                $lockAcquired = true;
            } else {
                if ($this->cache->acquireLock($cacheKey, self::REGENERATION_LOCK_TTL) === true) {
                    $lockAcquired = true;
                } else {
                    $waited = $this->waitForFresh($cacheKey);
                    if ($waited !== null) {
                        if ($waited->getCode() === 200) {
                            $notModified = $this->createNotModifiedResponse($request, $waited);
                            if ($notModified !== null) {
                                return $notModified;
                            }
                        }
                        return $this->attachCacheHeaders($waited, $this->resolveMaxAge($request, $waited), $waited->getHeader('etag'));
                    }
                    return new Response(render(__DIR__ . '/../templates/error.html.php', [
                        'message' => 'The feed is being generated by another request and did not become ready in time. Please retry shortly.',
                    ]), 504, ['cache-control' => 'no-store']);
                }
            }
        }

        try {
            $response = $next($request);
        } catch (\Throwable $e) {
            if ($lockAcquired === true) {
                $this->cache->releaseLock($cacheKey);
            }
            throw $e;
        }

        if ($lockAcquired === true) {
            $this->cache->releaseLock($cacheKey);
        }

        $code = $response->getCode();

        $backoffSeconds = self::toInt($request->getAttribute('_bridge_backoff'), 0);
        if ($backoffSeconds > 0) {
            $failureStatus = self::toInt($request->getAttribute('_bridge_failure_status'), $code === 200 ? 502 : $code);
            $this->writeBackoff($cacheKey, $failureStatus, $backoffSeconds);
        } elseif ($code === 200 && $request->getAttribute('_bridge_stale_data') !== true && $request->getAttribute('_bridge_error') !== true) {
            $this->clearBackoff($cacheKey);
        }

        if ($code === 200) {
            if ($request->getAttribute('_bridge_stale_data') === true) {
                $this->maybePrune();
                $maxAge = $backoffSeconds > 0 ? max(self::STALE_MIN_MAX_AGE, $backoffSeconds) : self::STALE_MIN_MAX_AGE;
                return $this->attachStaleHeaders($response, $maxAge);
            }

            $maxAge = $request->getAttribute('_bridge_error') === true ? 0 : $this->resolveMaxAge($request);
            $response = $this->attachCacheHeaders($response, $maxAge, $response->getHeader('etag'));

            $this->maybePrune();
            return $response;
        }

        if ($bypassCache === false && in_array($code, [400, 403, 404], true) === true) {
            $ttl = 60 + random_int(0, 120);
            $this->cache->set($cacheKey, $response, $ttl);
        }

        $this->maybePrune();

        return $response->withHeader('cache-control', 'no-store, no-cache, must-revalidate, max-age=0');
    }

    /**
     * Reads an active backoff marker, or null when none is present.
     *
     * @return array{status: int, until: int}|null
     */
    private function readBackoff(string $cacheKey): ?array
    {
        $value = $this->cache->get($cacheKey . self::BACKOFF_KEY_SUFFIX);
        if (is_array($value) === false) {
            return null;
        }
        $status = self::toInt($value['status'] ?? null, 0);
        $until = self::toInt($value['until'] ?? null, 0);
        if ($status < 400 || $until <= time()) {
            return null;
        }
        return ['status' => $status, 'until' => $until];
    }

    /**
     * Arms a backoff marker so subsequent requests skip upstream entirely.
     */
    private function writeBackoff(string $cacheKey, int $status, int $seconds): void
    {
        $seconds = max(1, min(86400, $seconds));
        $this->cache->set($cacheKey . self::BACKOFF_KEY_SUFFIX, [
            'status' => $status,
            'until' => time() + $seconds,
        ], $seconds);
    }

    /**
     * Clears the backoff marker after a successful fresh generation.
     */
    private function clearBackoff(string $cacheKey): void
    {
        $this->cache->delete($cacheKey . self::BACKOFF_KEY_SUFFIX);
    }

    /**
     * Serves a response during an active backoff window without touching
     * upstream: stale feed when available, otherwise the stored error code.
     *
     * @param array{status: int, until: int} $backoff
     */
    private function serveBackoff(array $backoff, ?Response $staleResponse): Response
    {
        if ($staleResponse !== null && $staleResponse->getCode() === 200) {
            $maxAge = max(self::STALE_MIN_MAX_AGE, $backoff['until'] - time());
            return $this->attachStaleHeaders($staleResponse, $maxAge);
        }

        $status = $backoff['status'];
        $label = Response::STATUS_CODES[$status] ?? 'Error';
        $body = render(__DIR__ . '/../templates/error.html.php', [
            'title' => sprintf('%d %s', $status, $label),
            'message' => 'The upstream source is temporarily unavailable. This feed is in a server-side backoff window and will retry automatically.',
        ]);

        return new Response($body, $status, [
            'cache-control' => 'no-store, no-cache, must-revalidate, max-age=0',
            'pragma' => 'no-cache',
        ]);
    }

    /**
     * Waits for a concurrent regeneration to publish a fresh response,
     * bounded by the client budget (FEED_TIMEOUT).
     */
    private function waitForFresh(string $cacheKey): ?Response
    {
        $budgetMs = (int) min(self::COLD_WAIT_MS, FeedDeadline::clientRemaining() * 1000);
        $waited = 0;
        while ($waited < $budgetMs) {
            usleep(self::COLD_POLL_MS * 1000);
            $waited += self::COLD_POLL_MS;
            $entry = $this->cache->getWithStale($cacheKey);
            $fresh = $entry['fresh'] ?? null;
            if ($fresh instanceof Response) {
                return $fresh;
            }
        }
        return null;
    }

    /**
     * Decorates a stale 200 response with short-lived cache headers.
     * No Retry-After is emitted: FreshRSS ignores it on 200 and the upstream
     * backoff is enforced server-side by the backoff marker.
     */
    private function attachStaleHeaders(Response $stale, int $maxAge): Response
    {
        $maxAge = max(self::STALE_MIN_MAX_AGE, $maxAge);

        $headers = [
            'x-feed-stale' => '1',
            'cache-control' => sprintf('public, max-age=%d, stale-while-revalidate=%d', $maxAge, self::REGENERATION_LOCK_TTL),
            'expires' => gmdate('D, d M Y H:i:s \G\M\T', time() + $maxAge),
        ];

        foreach ($headers as $name => $value) {
            $stale = $stale->withHeader($name, $value);
        }

        return $stale->withoutHeader(self::CACHE_TTL_HEADER)->withoutHeader('age')->withoutHeader('retry-after');
    }

    private function maybePrune(): void
    {
        if (random_int(1, 100) === 1) {
            $this->cache->prune();
        }
    }

    private function createNotModifiedResponse(Request $request, Response $cached): ?Response
    {
        $etag = $cached->getHeader('etag');
        $lastModified = $cached->getHeader('last-modified');

        $ifNoneMatch = $request->server('HTTP_IF_NONE_MATCH');
        if ($etag !== null && $ifNoneMatch !== null && self::etagMatches($ifNoneMatch, $etag) === true) {
            return new Response('', 304, self::createNotModifiedHeaders([
                'etag' => $etag,
                'last-modified' => $lastModified,
            ], $this->resolveMaxAge($request, $cached)));
        }

        $ifModifiedSince = $request->server('HTTP_IF_MODIFIED_SINCE');
        if ($ifNoneMatch !== null) {
            return null;
        }

        if ($ifModifiedSince !== null && $lastModified !== null) {
            $lastModifiedTimestamp = strtotime($lastModified);
            $modifiedSince = strtotime($ifModifiedSince);
            if ($lastModifiedTimestamp !== false && $modifiedSince !== false && $lastModifiedTimestamp <= $modifiedSince) {
                $modificationTimeGMT = gmdate('D, d M Y H:i:s \G\M\T', $lastModifiedTimestamp);
                return new Response('', 304, self::createNotModifiedHeaders([
                    'last-modified' => $modificationTimeGMT,
                    'etag' => $etag,
                ], $this->resolveMaxAge($request, $cached)));
            }
        }

        return null;
    }

    private function resolveMaxAge(Request $request, ?Response $cached = null): int
    {
        $attribute = $request->getAttribute('_resolved_cache_timeout');
        if (is_int($attribute) === true) {
            if ($attribute <= 0) {
                return 0;
            }
            return min(86400, $attribute);
        }

        if ($cached !== null) {
            $storedTtl = self::toInt($cached->getHeader(self::CACHE_TTL_HEADER), 0);
            if ($storedTtl > 0) {
                return min(86400, max(1, $storedTtl));
            }
        }

        $customTimeoutEnabled = filter_var(getenv('CACHE_CUSTOM_TIMEOUT'), FILTER_VALIDATE_BOOLEAN);
        if ($customTimeoutEnabled === true) {
            $paramInt = self::toInt($request->get('_cache_timeout'), 0);
            if ($paramInt > 0) {
                return min(86400, max(1, $paramInt));
            }
        }

        return self::DEFAULT_MAX_AGE;
    }

    private function attachCacheHeaders(Response $response, int $maxAge, ?string $etag = null): Response
    {
        if ($response->getCode() === 200 && $maxAge > 0) {
            if (($etag === null || $etag === '') === true) {
                $etag = '"' . md5($response->getBody()) . '"';
            }

            $staleWhileRevalidate = max(self::REGENERATION_LOCK_TTL, intdiv($maxAge, 4));

            return $response
            ->withHeader('etag', $etag)
            ->withHeader('cache-control', sprintf('public, max-age=%d, stale-while-revalidate=%d', $maxAge, $staleWhileRevalidate))
            ->withHeader('expires', gmdate('D, d M Y H:i:s \G\M\T', time() + $maxAge))
            ->withHeader('vary', 'Accept-Encoding')
            ->withoutHeader(self::CACHE_TTL_HEADER);
        }

        return $response
        ->withHeader('cache-control', 'no-store, no-cache, must-revalidate, max-age=0')
        ->withHeader('pragma', 'no-cache')
        ->withHeader('expires', gmdate('D, d M Y H:i:s \G\M\T'))
        ->withoutHeader(self::CACHE_TTL_HEADER);
    }

    /**
     * @return list<string>
     */
    private static function parseIfNoneMatch(string $value): array
    {
        $candidates = [];
        $length = strlen($value);
        $i = 0;

        while ($i < $length) {
            while ($i < $length && ($value[$i] === ' ' || $value[$i] === "\t" || $value[$i] === ',')) {
                $i++;
            }
            if ($i >= $length) {
                break;
            }

            if ($value[$i] === '"') {
                $start = ++$i;
                while ($i < $length && $value[$i] !== '"') {
                    if ($value[$i] === '\\' && ($i + 1) < $length) {
                        $i++;
                    }
                    $i++;
                }
                $candidates[] = substr($value, $start, $i - $start);
                if ($i < $length) {
                    $i++;
                }
            } else {
                $start = $i;
                while ($i < $length && $value[$i] !== ',') {
                    $i++;
                }
                $candidates[] = trim(substr($value, $start, $i - $start));
            }
        }

        return $candidates;
    }

    private static function etagMatches(string $ifNoneMatch, string $etag): bool
    {
        $ifNoneMatch = trim($ifNoneMatch);
        if ($ifNoneMatch === '*') {
            return true;
        }

        $target = self::normalizeEtag($etag);

        foreach (self::parseIfNoneMatch($ifNoneMatch) as $candidate) {
            $candidate = self::normalizeEtag($candidate);
            if ($candidate !== '' && $candidate === $target) {
                return true;
            }
        }

        return false;
    }

    private static function normalizeEtag(string $etag): string
    {
        $etag = trim($etag);
        if (str_starts_with($etag, 'W/') === true || str_starts_with($etag, 'w/') === true) {
            $etag = substr($etag, 2);
        }
        return trim($etag, '"');
    }

    /**
     * @param array<string, string|null> $validators
     * @return array<string, string>
     */
    private static function createNotModifiedHeaders(array $validators, int $maxAge): array
    {
        $staleWhileRevalidate = max(self::REGENERATION_LOCK_TTL, intdiv($maxAge, 4));
        $headers = self::addDateHeader([
            'vary' => 'Accept-Encoding',
            'cache-control' => sprintf('public, max-age=%d, stale-while-revalidate=%d', $maxAge, $staleWhileRevalidate),
            'expires' => gmdate('D, d M Y H:i:s \G\M\T', time() + $maxAge),
        ]);
        foreach ($validators as $name => $value) {
            if (is_string($value) === true && $value !== '') {
                $headers[$name] = $value;
            }
        }
        return $headers;
    }

    /**
     * @param array<string, string> $headers
     * @return array<string, string>
     */
    private static function addDateHeader(array $headers): array
    {
        if (isset($headers['date']) === false) {
            $headers['date'] = gmdate('D, d M Y H:i:s \G\M\T');
        }
        return $headers;
    }

    private static function toInt(mixed $value, int $default): int
    {
        if (is_int($value) === true) {
            return $value;
        }
        if (is_float($value) === true) {
            return (int) $value;
        }
        if (is_string($value) === true && is_numeric($value) === true) {
            return (int) $value;
        }
        return $default;
    }
}
